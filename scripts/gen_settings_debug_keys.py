"""Regenerates lib/controller/settings.debug_keys.dart: one `allKeys` list per settings class.

The list creates every lazy key at once, used to finish migrating a legacy file in one go and by tests.
`--check` only reports whether the file is stale (used by the pre-commit hook),
`test/settings_compat_test.dart` fails on a stale file too.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETTINGS_DIR = ROOT / 'lib' / 'controller'
OUT = SETTINGS_DIR / 'settings.debug_keys.dart'

CLASS_RE = re.compile(r'^class (\w+) extends _SettingsKeysWriter \{', re.M)
KEY_RE = re.compile(r'^  late final (\w+)\s*=\s*_key\w*\s*[<(]', re.M)


def generate():
    classes = []
    for path in sorted(SETTINGS_DIR.glob('settings*.dart')):
        if path.name == OUT.name:
            continue
        text = path.read_text(encoding='utf-8')
        for cls_match in CLASS_RE.finditer(text):
            cls = cls_match.group(1)
            end = text.find('\n}\n', cls_match.end())
            body = text[cls_match.end():end]
            classes.append((cls, KEY_RE.findall(body)))

    lines = [
        '// generated by scripts/gen_settings_debug_keys.py, do not edit.',
        '// ignore_for_file: library_private_types_in_public_api',
        "part of 'settings_controller.dart';",
        '',
    ]
    for cls, keys in classes:
        lines.append(f'extension {cls.lstrip("_")}DebugKeys on {cls} {{')
        lines.append('  List<RxBase<Object?>> get allKeys => [')
        for key in keys:
            lines.append(f'    {key},')
        lines.append('  ];')
        lines.append('}')
        lines.append('')
    lines.append('List<RxBase<Object?>> _allSettingsKeys(_SettingsKeysWriter writer) => switch (writer) {')
    for cls, _ in classes:
        lines.append(f'  {cls} w => w.allKeys,')
    lines.append('};')
    lines.append('')
    return '\n'.join(lines), sum(len(keys) for _, keys in classes), len(classes)


def main():
    content, key_count, class_count = generate()
    current = OUT.read_text(encoding='utf-8').replace('\r\n', '\n') if OUT.exists() else ''
    if '--check' in sys.argv:
        if current != content:
            print(f'{OUT.relative_to(ROOT)} is stale, run scripts/gen_settings_debug_keys.py', file=sys.stderr)
            sys.exit(1)
        return
    if current == content:
        print(f'{OUT.name}: up to date ({key_count} keys in {class_count} classes)')
        return
    OUT.write_text(content, encoding='utf-8', newline='\n')
    print(f'{OUT.name}: {key_count} keys in {class_count} classes')


if __name__ == '__main__':
    main()
