sealed class SubtitleTrack {
  const SubtitleTrack();

  /// stable identifier, used to persist the selection & to compare tracks.
  String get id;

  String get displayName;

  /// empty when unknown.
  String get languageCode;

  /// native language name (`English`), falls back to the raw code.
  String get languageName {
    final code = languageCode;
    if (code.isEmpty) return '';
    final normalized = normalizeLanguageCode(code);
    final name = NamidaLanguage.fromCode(normalized.isEmpty ? code : normalized).name;
    return name == '?' ? code : name;
  }

  bool get isAutoGenerated => false;

  /// short format name for display, empty when unknown.
  String get codecName => '';

  /// a local file the player can load, null for tracks the player already demuxes itself.
  Future<File?> ensureLocalFile() => Future.value(null);

  /// reduces any language tag to a bare ISO 639-1 code when possible.
  ///
  /// `eng` => `en`, `pt-BR` => `pt`, `zh-Hans` => `zh`, `en_US` => `en`.
  static String normalizeLanguageCode(String code) {
    if (code.isEmpty) return code;

    var base = code;
    for (int i = 0; i < code.length; i++) {
      final c = code.codeUnitAt(i);
      if (c == 0x2D /* - */ || c == 0x5F /* _ */ ) {
        base = code.substring(0, i);
        break;
      }
    }

    base = base.toLowerCase();
    if (base.length != 3) return base;
    return _iso6392To6391[base] ?? base;
  }
}

/// a track the player demuxes from the media itself, selected through its own id.
class SubtitleTrackPlayer extends SubtitleTrack {
  final TextTrack textTrack;

  const SubtitleTrackPlayer(this.textTrack);

  /// what the player expects back in `setTextTrack`, same fallback the platforms use.
  static String idOf(TextTrack textTrack) => textTrack.id ?? '${textTrack.groupIndex}:${textTrack.trackIndex}';

  String get playerTrackId => idOf(textTrack);

  @override
  String get id => 'player_$playerTrackId';

  @override
  String get displayName {
    final label = textTrack.label;
    if (label != null && label.isNotEmpty) return label;
    final language = textTrack.language;
    if (language != null && language.isNotEmpty) return language;
    return '#${textTrack.trackIndex}';
  }

  @override
  String get languageCode => textTrack.language ?? '';

  /// image based, can only be shown by a player that draws subtitles itself.
  bool get isBitmap => switch (textTrack.mimeType) {
    'application/pgs' || 'application/vobsub' || 'application/dvbsubs' => true,
    'hdmv_pgs_subtitle' || 'dvd_subtitle' || 'dvb_subtitle' || 'xsub' => true,
    _ => false,
  };

  @override
  String get codecName {
    final mime = textTrack.mimeType;
    if (mime == null || mime.isEmpty) return '';
    return switch (mime) {
      'application/x-subrip' || 'subrip' => 'srt',
      'text/x-ssa' => 'ass',
      'text/vtt' || 'application/x-mp4-vtt' || 'webvtt' => 'vtt',
      'application/x-quicktime-tx3g' || 'mov_text' => 'tx3g',
      'application/ttml+xml' => 'ttml',
      'application/pgs' || 'hdmv_pgs_subtitle' => 'pgs',
      'application/vobsub' || 'dvd_subtitle' => 'vobsub',
      'application/dvbsubs' || 'dvb_subtitle' => 'dvb',
      _ => mime.substring(mime.lastIndexOf('/') + 1),
    };
  }
}

class SubtitleTrackFile extends SubtitleTrack {
  final File file;

  const SubtitleTrackFile(this.file);

  @override
  String get id => 'file_${file.path}';

  @override
  String get displayName => file.path.getFilename;

  @override
  String get languageCode => '';

  @override
  Future<File?> ensureLocalFile() => Future.value(file);
}

class SubtitleTrackYoutube extends SubtitleTrack {
  final String videoId;
  final Caption caption;

  const SubtitleTrackYoutube({
    required this.videoId,
    required this.caption,
  });

  @override
  String get id => 'yt_${caption.vssId ?? caption.code}';

  @override
  String get displayName => caption.name.isNotEmpty ? caption.name : caption.code;

  @override
  String get languageCode => caption.code;

  @override
  bool get isAutoGenerated => caption.autoGenerated;

  File get cacheFile {
    final name = DownloadTaskFilename.cleanupFilename(
      '${videoId}_${caption.vssId ?? caption.code}',
      parentDirPath: AppDirs.SUBTITLES,
    );
    return FileParts.join(AppDirs.SUBTITLES, '$name.vtt');
  }

  static final _fmtParamRegex = RegExp(r'[?&]fmt=[^&]*');

  /// `fmt=vtt` also carries inline word timestamps for auto generated captions,
  /// which end up parsed as karaoke parts.
  String get _requestUrl => '${caption.url.replaceAll(_fmtParamRegex, '')}&fmt=vtt';

  /// caption urls expire after a few hours, so the fetched file is kept around.
  @override
  Future<File?> ensureLocalFile() async {
    final cacheFile = this.cacheFile;
    if (await cacheFile.existsAndValid(16)) return cacheFile;

    if (caption.url.isEmpty) return null;

    HttpClientWrapper? client;
    try {
      client = HttpClientWrapper.createSync();
      final res = await client.getUrl(_requestUrl, cancelToken: null);
      final body = res.body;
      if (body.isEmpty) return null;
      await cacheFile.writeAsString(body);
      return cacheFile;
    } catch (_) {
      return null;
    } finally {
      client?.close().ignoreError();
    }
  }
}

